def enc(t):
    b = bytearray()
    for r in t:
        lo = hi = 0
        for x in range(8):
            lo |= (r[x] & 1) << (7 - x)
            hi |= (r[x] >> 1) << (7 - x)
        b += bytes([lo, hi])
    return b


